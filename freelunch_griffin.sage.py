def freelunch_attack(n_rounds):
    print("=" * _sage_const_60 )
    print(f"FreeLunch attack on Griffin-pi")
    print(f"  p={p}, t={t}, alpha={alpha}, R={n_rounds}")
    print("=" * _sage_const_60 )

    # --- Step 1: sysGen ---
    print("\n[1/4] sysGen: building FreeLunch polynomial system...")
    system = sys_gen(n_rounds)
    print(f"  Generated {len(system)} polynomials in {PR.ngens()} variables.")
    print(f"  Equations:")
    for i, eq in enumerate(system):
        lm = eq.lm()
        print(f"    p[{i}]: LM = {lm},  #terms = {len(eq.monomials())}")

    # Rewrite system in the FreeLunch ring with weighted order
    print("\n  Re-expressing in FreeLunch weighted deglex ring...")
    PR_fl = make_freelunch_ring(n_rounds)

    # Use a ring homomorphism PR -> PR_fl (same variables, same Fp, new order).
    # hom() is the safest way: avoids string-parsing surprises.
    # PR has n_rounds+1 active vars (x0, u1..u_{n_rounds}) but was built with
    # R vars total.  PR_fl has exactly n_rounds+1 vars.  Map them by position.
    phi = PR.hom([PR_fl.gen(i) for i in range(n_rounds + _sage_const_1 )]
                 + [PR_fl(_sage_const_0 )] * (PR.ngens() - (n_rounds + _sage_const_1 )),
                 PR_fl)
    system_fl = [phi(eq) for eq in system]
    print("  FreeLunch ring order:", PR_fl.term_order())
    print("  Leading monomials in FreeLunch order:")
    for i, eq in enumerate(system_fl):
        print(f"    p[{i}]: LM = {eq.lm()}")

    # Confirm it is a FreeLunch system (Proposition 4):
    # all leading monomials should be pure powers of a single variable.
    lms = [eq.lm() for eq in system_fl]
    print(f"\n  FreeLunch check: LMs = {lms}")
    is_fl = all(sum(_sage_const_1  for e in lm.exponents()[_sage_const_0 ] if e > _sage_const_0 ) == _sage_const_1  for lm in lms)
    print(f"  Is FreeLunch system: {is_fl}")
    if not is_fl:
        print("  WARNING: Not a FreeLunch system — check encoding!")

    # --- Step 2: matGen ---
    print("\n[2/4] matGen: computing multiplication matrix T0...")
    alpha0, DH, Mi_list, B_H = mat_gen(system_fl, PR_fl, n_rounds)
    print(f"  alpha0 = {alpha0},  DH = {DH}")
    print(f"  M_i blocks (sizes {DH}x{DH}):  {len(Mi_list)} blocks")

    # --- Step 3: polyDet ---
    print("\n[3/4] polyDet: computing det(x0^alpha0 * I + sum x0^i * M_i)...")
    f = poly_det(alpha0, DH, Mi_list)
    print(f"  Degree of f(x0) = {f.degree()}")
    print(f"  f(x0) = {f}")

    # --- Step 4: uniSol ---
    print("\n[4/4] uniSol: finding roots of f(x0)...")
    roots = uni_sol(f)
    print(f"  Found {len(roots)} root(s): {roots}")

    # --- Verification ---
    print("\nVerification:")
    for rv in roots:
        ok, out = verify_cico(rv, n_rounds)
        #inp = [Fp(0)] + [Fp(rv)] + [Fp(0)] * (t - 2)
        inp = [Fp(_sage_const_0 ), Fp(_sage_const_31 *rv+_sage_const_3 ), Fp(_sage_const_3 *rv), Fp(rv+_sage_const_1 ), Fp(_sage_const_7 *rv+_sage_const_43 ), Fp(_sage_const_2 *rv+_sage_const_1 ), Fp(_sage_const_4 *rv+_sage_const_2 ), 
            Fp(_sage_const_6 *rv+_sage_const_12 ), Fp(_sage_const_9 *rv+_sage_const_36 ), Fp(_sage_const_3 *rv+_sage_const_3 ), Fp(_sage_const_4 *rv+_sage_const_7 ), Fp(_sage_const_2 *rv+_sage_const_10 )]
        print(f"  x0 = {rv}")
        print(f"  input[0]  = {inp[_sage_const_0 ]},  output[0] = {out[_sage_const_0 ]},  CICO OK: {ok}")
        print(f"Input state = {inp}")
        print(f"Output state = {out}")

    return roots


