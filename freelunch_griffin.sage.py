# ---------------------------------------------------------------------------
# FreeLunch order  (Construction 1 / Definition 2)
# ---------------------------------------------------------------------------
# The FreeLunch order is a weighted deglex order (Definition 2) with weights:
#   wt(x0) = 1
#   wt(u_i) = wt(LM_{<_T}(q_i)) / alpha_i
#
# For Griffin the naive encoding gives every auxiliary variable the role of
# capturing x^{1/alpha}, so alpha_i = alpha for all i, and the weight
# of q_i (the argument to x^{1/alpha} in round i) grows as (2*alpha+1)^{i-1}.
# Hence:
#   wt(u_i) = (2*alpha+1)^{i-1} / alpha
#
# We encode this as integer weights (scaled by alpha^R to stay integral).

def freelunch_weights(n_rounds):
    """
    Return integer weight vector [wt(x0), wt(u1), ..., wt(u_{n_rounds})]
    for the FreeLunch (triangular) order.
    """
    # d_{<=i} = (2*alpha+1)^i   (degree of G_i composed)
    d = _sage_const_2  * alpha + _sage_const_1           # degree per round for Griffin
    # wt(x0) = 1  (scaled)
    # wt(u_i) = d^{i-1} / alpha  =>  multiply through by alpha
    weights = [_sage_const_1 ]              # for x0
    for i in range(_sage_const_1 , n_rounds + _sage_const_1 ):
        weights.append(d**(i - _sage_const_1 ))   # = alpha * wt(u_i), integer
    return weights


def make_freelunch_ring(n_rounds):
    """
    Return a polynomial ring with the FreeLunch weighted deglex order.

    SageMath supports weighted degree lex orders via
      TermOrder('wdeglex', weights)
    which orders monomials first by weighted degree then lexicographically
    (with the LAST variable being largest in lex — we reverse var order so
    x0 < u1 < ... < u_R in the lex tiebreak, matching the paper).
    """
    weights = freelunch_weights(n_rounds)
    # SageMath's 'wdeglex' uses the weight vector directly.
    to = TermOrder('wdeglex', tuple(weights))
    names = ["x0"] + [f"u{i}" for i in range(_sage_const_1 , n_rounds + _sage_const_1 )]
    return PolynomialRing(Fp, names, order=to)


# ---------------------------------------------------------------------------
# Step 2 – matGen: compute the multiplication matrix T0
# ---------------------------------------------------------------------------
# Lemma 1 of the paper: under the FreeLunch basis ordering
#
#   B = [phi_1, ..., phi_{DH},
#        x0*phi_1, ..., x0*phi_{DH},
#        ...,
#        x0^{alpha0-1}*phi_1, ..., x0^{alpha0-1}*phi_{DH}]
#
# the matrix T0 (multiplication by x0) has the block-companion structure:
#
#   T0 = [  0       0   ...  0   -M0   ]
#        [  I       0   ...  0   -M1   ]
#        [  0       I   ...  0   -M2   ]
#        [  ...                  ...   ]
#        [  0   ...     I   -M_{alpha0-1} ]
#
# We compute the M_i blocks by reducing x0^{alpha0} * phi_j modulo the ideal
# and reading off the coefficients.

def mat_gen(system_fl, PR_fl, n_rounds):
    """
    Compute the block matrices M0..M_{alpha0-1} defining T0.

    Parameters
    ----------
    system_fl : list of polynomials in PR_fl (the FreeLunch system)
    PR_fl     : PolynomialRing with FreeLunch order
    n_rounds  : number of Griffin rounds

    Returns
    -------
    alpha0  : int     (degree of x0 in the leading monomial of g)
    DH      : int     (dimension of the H subspace = product of alpha_i)
    Mi_list : list of alpha0 matrices over Fp  (M0 .. M_{alpha0-1})
    B_H     : list of monomials (basis of H, i.e. monomials not involving x0)
    """
    x0_fl = PR_fl.gen(_sage_const_0 )

    # --- Normal basis --------------------------------------------------
    # We need the standard monomials (basis of R/I) w.r.t. the FreeLunch
    # order.  SageMath's ideal.normal_basis() calls Singular, which uses
    # the ring's term order — so as long as PR_fl carries the wdeglex order
    # this is correct.
    I_fl  = PR_fl.ideal(system_fl)
    B_all = I_fl.normal_basis()   # monomials not in LT(I) under FreeLunch order

    # H-basis: monomials with x0-exponent == 0
    B_H = [m for m in B_all if m.degree(x0_fl) == _sage_const_0 ]

    DH     = len(B_H)
    DI     = len(B_all)
    alpha0 = DI // DH      # degree of x0 in LM(g)

    print(f"  DI = {DI},  DH = {DH},  alpha0 = {alpha0}")

    B_H_idx = {m: j for j, m in enumerate(B_H)}

    # --- Polynomial reduction ------------------------------------------
    # CRITICAL: I_fl.reduce(f) calls Singular's reduce() using the ring's
    # stored term order, which IS the FreeLunch wdeglex order (since PR_fl
    # was built with that order).  However, Singular's reduce() requires the
    # input list to already be a Gröbner basis — and system_fl IS one by the
    # FreeLunch property.  We make this explicit by passing the GB directly.
    #
    # SageMath syntax:  f.reduce(G)  where G is a list of polynomials
    # that form a GB, performs multivariate division and returns the normal
    # form.  This respects the ring's term order.

    # Verify system_fl is the GB (it should be by construction)
    GB = system_fl   # FreeLunch system is already a GB in its order

    # --- Build M_i blocks ----------------------------------------------
    # Lemma 1: T0 has block-companion form with blocks M_0..M_{alpha0-1}.
    # From the reduction:
    #   x0^{alpha0} * phi_j  ≡  rem  (mod I)
    # where rem = sum_{k,l} c_{k,l} * x0^k * B_H[l],
    # and by Lemma 1:  rem = -sum_k sum_l M_k[l,j] * x0^k * B_H[l]
    # => M_k[l,j] = -c_{k,l}
    Mi_list = [matrix(Fp, DH, DH) for _ in range(alpha0)]

    for j, phi in enumerate(B_H):
        poly_to_reduce = x0_fl**alpha0 * phi
        # .reduce(GB) performs division with remainder w.r.t. the ring's
        # term order (our FreeLunch wdeglex), returning the normal form.
        rem = poly_to_reduce.reduce(GB)
        for mono, coef in zip(rem.monomials(), rem.coefficients()):
            k_exp = mono.degree(x0_fl)
            # Divide out x0^k to isolate the B_H component
            base = PR_fl(mono // (x0_fl**k_exp)) if k_exp > _sage_const_0  else PR_fl(mono)
            if base in B_H_idx:
                l = B_H_idx[base]
                Mi_list[k_exp][l, j] = -Fp(coef)

    # Sanity: warn if all blocks are zero (means reduce() silently did nothing)
    nonzero_blocks = sum(_sage_const_1  for M in Mi_list if not M.is_zero())
    print(f"  Non-zero M_i blocks: {nonzero_blocks} / {alpha0}")
    if nonzero_blocks == _sage_const_0 :
        print("  WARNING: all M_i are zero. .reduce() likely ignored the term order.")
        print("  Ensure system_fl polynomials live in PR_fl (the wdeglex ring).")

    return alpha0, DH, Mi_list, B_H


# ---------------------------------------------------------------------------
# Step 3 – polyDet: compute det via Lemma 2
# ---------------------------------------------------------------------------
# Lemma 2:
#   det(x0 * I_{DI} - T0) = ± det( x0^{alpha0} * I_{DH}
#                                   + sum_{i=0}^{alpha0-1} x0^i * M_i )
#
# The right-hand side is the determinant of a DH×DH matrix whose entries
# are polynomials in x0 of degree <= alpha0.  We evaluate it at sufficiently
# many points and interpolate (or use a symbolic DH×DH determinant).

def poly_det(alpha0, DH, Mi_list):
    """
    Compute the univariate polynomial
        f(x0) = det( x0^alpha0 * I_DH + sum_{i=0}^{alpha0-1} x0^i * M_i )
    by evaluating at DH*alpha0 + 1 points and interpolating.

    Returns
    -------
    f : polynomial in Fp[x0]  of degree  DH * alpha0
    """
    Fx = PolynomialRing(Fp, 'x')
    xv = Fx.gen()

    deg_f = DH * alpha0    # degree of f(x0)
    n_pts = deg_f + _sage_const_1 

    if n_pts > p:
        raise ValueError("Field too small for interpolation; use a larger prime.")

    eval_pts  = [Fp(i) for i in range(n_pts)]
    eval_vals = []

    for pt in eval_pts:
        # Build the DH x DH matrix at x0 = pt
        A = pt**alpha0 * identity_matrix(Fp, DH)
        for i in range(alpha0):
            A = A + pt**i * Mi_list[i]
        eval_vals.append(A.determinant())

    f = Fx.lagrange_polynomial(list(zip(eval_pts, eval_vals)))
    return f


