def griffin_eval(input_vec, n_rounds):
    """
    Evaluate Griffin-pi numerically on input_vec (list of Fp elements).
    Returns the output vector.
    """
    # Initial affine layer: state = M * input  (Griffin applies M before round 1)
    # Actually Griffin-pi is:  G^pi = F_R o ... o F_1 o (M * .)
    # where F_i(s) = c^{(i)} + M * S(s)
    state = list(M_mat * vector(Fp, input_vec))

    for rnd in range(n_rounds):
        # Non-linear layer S
        y0_val = state[_sage_const_0 ]**((p - _sage_const_1  + alpha) // alpha % (p - _sage_const_1 ))  # x^{1/alpha} in Fp
        # More correctly: find y such that y^alpha = state[0]
        # In Fp with gcd(alpha,p-1)=1, x^{1/alpha} = x^{inv_alpha mod (p-1)}
        inv_a  = pow(int(alpha), -_sage_const_1 , p - _sage_const_1 )
        y0_val = pow(int(state[_sage_const_0 ]), inv_a, p)
        y1_val = pow(int(state[_sage_const_1 ]), alpha, p)

        nl = [Fp(y0_val), Fp(y1_val)]
        for i in range(_sage_const_2 , t):
            li_val = Fp((i - _sage_const_1 )) * Fp(y0_val) + Fp(y1_val) + state[i - _sage_const_1 ]
            nl.append(state[i] * (li_val**_sage_const_2  + deltas[i] * li_val + mus[i]))

        # Affine layer
        state = list(M_mat * vector(Fp, nl) + RC[rnd])

    return state


